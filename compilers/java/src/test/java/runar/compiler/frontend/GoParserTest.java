    private static final String P2PKH_SOURCE = """
        package contract

        import runar "github.com/icellan/runar/packages/runar-go"

        // P2PKH — Pay-to-Public-Key-Hash.
        type P2PKH struct {
        \trunar.SmartContract
        \tPubKeyHash runar.Addr `runar:"readonly"`
        }

        // Unlock verifies the pubKey hashes to the committed hash, then checks the signature.
        func (c *P2PKH) Unlock(sig runar.Sig, pubKey runar.PubKey) {
        \trunar.Assert(runar.Hash160(pubKey) == c.PubKeyHash)
        \trunar.Assert(runar.CheckSig(sig, pubKey))
        }
        """;

    private static final String COUNTER_SOURCE = """
        package contract

        import runar "github.com/icellan/runar/packages/runar-go"

        type Counter struct {
        \trunar.StatefulSmartContract
        \tCount runar.Bigint
        \tOwner runar.Addr `runar:"readonly"`
        }

        func (c *Counter) Increment() {
        \tc.Count++
        }

        func (c *Counter) Decrement() {
        \trunar.Assert(c.Count > 0)
        \tc.Count--
        }
        """;

    @Test
    void parsesP2pkhIntoExpectedContractShape() throws Exception {
        ContractNode c = GoParser.parse(P2PKH_SOURCE, "P2PKH.runar.go");
        assertEquals("P2PKH", c.name());
        assertEquals(ParentClass.SMART_CONTRACT, c.parentClass());
        assertEquals("P2PKH.runar.go", c.sourceFile());
        assertEquals(1, c.properties().size());

        PropertyNode pkh = c.properties().get(0);
        assertEquals("pubKeyHash", pkh.name());
        assertTrue(pkh.readonly());
        assertEquals(new PrimitiveType(PrimitiveTypeName.ADDR), pkh.type());
        assertNull(pkh.initializer());
    }

    @Test
    void parsesP2pkhAutoGeneratedConstructor() throws Exception {
        ContractNode c = GoParser.parse(P2PKH_SOURCE, "P2PKH.runar.go");
        var ctor = c.constructor();
        assertEquals("constructor", ctor.name());
        assertEquals(Visibility.PUBLIC, ctor.visibility());
        assertEquals(1, ctor.params().size());
        assertEquals("pubKeyHash", ctor.params().get(0).name());

        // Body: super(pubKeyHash); this.pubKeyHash = pubKeyHash;
        assertEquals(2, ctor.body().size());

        var superStmt = (ExpressionStatement) ctor.body().get(0);
        var superCall = (CallExpr) superStmt.expression();
        assertEquals("super", ((Identifier) superCall.callee()).name());
        assertEquals(1, superCall.args().size());
        assertEquals("pubKeyHash", ((Identifier) superCall.args().get(0)).name());

        var assign = (AssignmentStatement) ctor.body().get(1);
        assertEquals("pubKeyHash", ((PropertyAccessExpr) assign.target()).property());
        assertEquals("pubKeyHash", ((Identifier) assign.value()).name());
    }

    @Test
    void parsesP2pkhUnlockBuiltinCalls() throws Exception {
        ContractNode c = GoParser.parse(P2PKH_SOURCE, "P2PKH.runar.go");
        assertEquals(1, c.methods().size());
        var unlock = c.methods().get(0);
        assertEquals("unlock", unlock.name());
        assertEquals(Visibility.PUBLIC, unlock.visibility());
        assertEquals(2, unlock.params().size());
        assertEquals("sig", unlock.params().get(0).name());
        assertEquals(new PrimitiveType(PrimitiveTypeName.SIG), unlock.params().get(0).type());
        assertEquals("pubKey", unlock.params().get(1).name());
        assertEquals(new PrimitiveType(PrimitiveTypeName.PUB_KEY), unlock.params().get(1).type());

        assertEquals(2, unlock.body().size());

        // assert(hash160(pubKey) === this.pubKeyHash)
        var assertStmt = (ExpressionStatement) unlock.body().get(0);
        var assertCall = (CallExpr) assertStmt.expression();
        assertEquals("assert", ((Identifier) assertCall.callee()).name());
        var cmp = (BinaryExpr) assertCall.args().get(0);
        assertEquals(Expression.BinaryOp.EQ, cmp.op());
        var hashCall = (CallExpr) cmp.left();
        assertEquals("hash160", ((Identifier) hashCall.callee()).name());
        assertEquals("pubKey", ((Identifier) hashCall.args().get(0)).name());
        assertEquals("pubKeyHash", ((PropertyAccessExpr) cmp.right()).property());

        // assert(checkSig(sig, pubKey))
        var assertStmt2 = (ExpressionStatement) unlock.body().get(1);
        var assertCall2 = (CallExpr) assertStmt2.expression();
        assertEquals("assert", ((Identifier) assertCall2.callee()).name());
        var checkSig = (CallExpr) assertCall2.args().get(0);
        assertEquals("checkSig", ((Identifier) checkSig.callee()).name());
        assertEquals(2, checkSig.args().size());
    }

    @Test
    void parsesStatefulCounterWithReadonlyAndMutableFields() throws Exception {
        ContractNode c = GoParser.parse(COUNTER_SOURCE, "Counter.runar.go");
        assertEquals("Counter", c.name());
        assertEquals(ParentClass.STATEFUL_SMART_CONTRACT, c.parentClass());
        assertEquals(2, c.properties().size());

        PropertyNode count = c.properties().get(0);
        assertEquals("count", count.name());
        assertFalse(count.readonly(), "Count without struct tag must be mutable");
        assertEquals(new PrimitiveType(PrimitiveTypeName.BIGINT), count.type());

        PropertyNode owner = c.properties().get(1);
        assertEquals("owner", owner.name());
        assertTrue(owner.readonly(), "Owner with `runar:\"readonly\"` tag must be readonly");
        assertEquals(new PrimitiveType(PrimitiveTypeName.ADDR), owner.type());
    }

    @Test
    void parsesStatefulCounterMethods() throws Exception {
        ContractNode c = GoParser.parse(COUNTER_SOURCE, "Counter.runar.go");
        assertEquals(2, c.methods().size());

        var inc = c.methods().get(0);
        assertEquals("increment", inc.name());
        assertEquals(Visibility.PUBLIC, inc.visibility());
        assertEquals(1, inc.body().size());
        var incStmt = (ExpressionStatement) inc.body().get(0);
        var incExpr = (IncrementExpr) incStmt.expression();
        assertFalse(incExpr.prefix(), "c.Count++ is postfix");
        assertEquals("count", ((PropertyAccessExpr) incExpr.operand()).property());

        var dec = c.methods().get(1);
        assertEquals("decrement", dec.name());
        assertEquals(2, dec.body().size());
        // assert(this.count > 0)
        var assertStmt = (ExpressionStatement) dec.body().get(0);
        var assertCall = (CallExpr) assertStmt.expression();
        assertEquals("assert", ((Identifier) assertCall.callee()).name());
        var cmp = (BinaryExpr) assertCall.args().get(0);
        assertEquals(Expression.BinaryOp.GT, cmp.op());
        assertEquals("count", ((PropertyAccessExpr) cmp.left()).property());
        assertInstanceOf(BigIntLiteral.class, cmp.right());
        assertEquals(BigInteger.ZERO, ((BigIntLiteral) cmp.right()).value());
        // c.Count--
        var decStmt = (ExpressionStatement) dec.body().get(1);
        assertInstanceOf(DecrementExpr.class, decStmt.expression());
    }

