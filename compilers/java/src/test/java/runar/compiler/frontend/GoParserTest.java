    @Test
    void initMethodIsFoldedIntoPropertyInitializers() throws Exception {
        String src = """
            package contract

            import runar "github.com/icellan/runar/packages/runar-go"

            type C struct {
            \trunar.StatefulSmartContract
            \tCount runar.Bigint
            \tFlag runar.Bool
            }

            func (c *C) init() {
            \tc.Count = 7
            \tc.Flag = true
            }
            """;
        ContractNode c = GoParser.parse(src, "C.runar.go");
        // init must not appear as a method.
        for (var m : c.methods()) {
            if ("init".equals(m.name())) {
                throw new AssertionError("init() should be folded into property initializers");
            }
        }
        var count = c.properties().get(0);
        assertNotNull(count.initializer(), "Count initializer must be set");
        assertEquals(BigInteger.valueOf(7), ((BigIntLiteral) count.initializer()).value());

        var flag = c.properties().get(1);
        assertNotNull(flag.initializer(), "Flag initializer must be set");

        // Constructor params must exclude initialised properties.
        assertEquals(0, c.constructor().params().size());
    }

