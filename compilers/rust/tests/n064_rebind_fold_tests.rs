//! N-064 — constant folding must not fold with a constant a name no longer
//! holds. Port of the reference tier's case in
//! packages/runar-compiler/src/__tests__/optimizer.test.ts.
//!
//! The folder recorded a name's constant when a binding produced one and never
//! dropped it. A name can be bound more than once, and the probes that showed
//! it bound a user local to the name of an earlier compiler temp: with folding
//! ON (the default) Rebind's guard became OP_TRUE (7600a0695151515177777777,
//! spendable with any p > 0), RebindEq's became OP_FALSE, and a rebinding
//! inside an if arm or a loop body leaked the same way past the if / into
//! later iterations.
//!
//! N-065 made that naming collision a refusal, so the probe SOURCES no longer
//! compile (asserted below). The fold must still be right for the ANF shape,
//! so this test replays the exact ANF each probe lowered to
//! (conformance/negatives/n064-collision-anf.json, generated by parse ->
//! lowerToANF with no validator) through the IR loader and this tier's
//! constant folder (`compile_from_program_with_options` with folding ON),
//! then lowers and emits it. On that replay the reference tier's pre-N-064
//! folder reproduces each probe's `staleFoldOn` script byte for byte, so the
//! replay keeps the regression value the source probes had.
//!
//! Proves: the four probe sources are refused with the N-065 diagnostic, and
//! this tier's folder turns each collision ANF into the fold-OFF bytes every
//! tier emits (never the stale script). Does NOT prove on-chain behaviour —
//! the Spend-engine proof is
//! packages/runar-testing/src/__tests__/n064-rebind-fold-spend.test.ts.

use runar_compiler_rust::ir::loader::load_ir_from_str;
use runar_compiler_rust::{compile_from_program_with_options, compile_from_source_str_with_result, CompileOptions};

fn corpus() -> serde_json::Value {
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../conformance/negatives/n064-collision-anf.json");
    serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap()
}

/// The local each probe spells like a temp — the name N-065 refuses.
fn colliding_local(probe: &str) -> &'static str {
    match probe {
        "Rebind" | "RebindEq" => "t1",
        "IfStale" | "LoopStale" => "t2",
        other => panic!("unknown probe {}", other),
    }
}

#[test]
fn n064_probe_sources_are_refused_by_n065() {
    let c = corpus();
    for p in c["probes"].as_array().unwrap() {
        let name = p["name"].as_str().unwrap();
        let file = format!("{}.runar.ts", name);
        let r = compile_from_source_str_with_result(p["source"].as_str().unwrap(), Some(&file), &CompileOptions::default());
        let want = format!(
            "'{}' is reserved for compiler-generated names and cannot be used as an identifier",
            colliding_local(name)
        );
        assert!(!r.success, "{} compiled", name);
        assert!(
            r.diagnostics.iter().any(|d| d.message == want),
            "{}: {:?}",
            name,
            r.diagnostics.iter().map(|d| d.message.clone()).collect::<Vec<_>>()
        );
    }
}

#[test]
fn n064_fold_on_does_not_use_a_stale_constant() {
    let c = corpus();
    let probes = c["probes"].as_array().unwrap();
    assert_eq!(probes.len(), 4);
    let mut failures = Vec::new();
    for p in probes {
        let name = p["name"].as_str().unwrap();
        let fold_off = p["foldOff"].as_str().unwrap();
        let stale = p["staleFoldOn"].as_str().unwrap();
        assert_ne!(fold_off, stale);
        let program = load_ir_from_str(&p["ir"].to_string()).unwrap_or_else(|e| panic!("{} ANF refused: {}", name, e));
        for disable_fold in [true, false] {
            let opts = CompileOptions { disable_constant_folding: disable_fold, ..CompileOptions::default() };
            let got = compile_from_program_with_options(&program, &opts)
                .unwrap_or_else(|e| panic!("{} fold-off={}: {}", name, disable_fold, e))
                .script;
            if got != fold_off {
                failures.push(format!("{} fold-off={}: want {}, got {}", name, disable_fold, fold_off, got));
            }
        }
    }
    assert!(failures.is_empty(), "{}", failures.join("\n"));
}
