"""F-239: the Python SDK's generated typed wrappers emit `satoshis=None` for
every stateful call that passes an options object without an explicit
satoshis value.  `codegen.py`'s `{Contract}StatefulCallOptions._to_call_options`
converted the dataclass default (0) into None (`satoshis=self.satoshis or
None`); `contract.py`'s stateful-call path then does `if opts.satoshis > 0:`,
which every non-multi-output stateful call reaches, raising
`TypeError: '>' not supported between instances of 'NoneType' and 'int'`.

Matches the TS SDK: `CallOptions.satoshis` is "unspecified" when the caller
doesn't set it, and the SDK falls back to the spent UTXO's value
(packages/runar-sdk/src/contract.ts:1459 --
`options?.satoshis ?? singleExplicitStateSats ?? this.currentUtxo.satoshis`,
using `??` so None/undefined -- not 0 -- means "unset"). The Python
`CallOptions.satoshis` field is declared as a plain `int = 0` (not
`Optional[int]`), so 0 is already the SDK's own "unspecified" sentinel
(contract.py: `if opts.satoshis > 0:`); codegen's `or None` just broke the
type contract on top of that without changing the sentinel's meaning.

Proves: a wrapper generated by `runar.sdk.codegen.generate_python` for a real
compiled stateful contract (Counter) can make a stateful call with a freshly
constructed `CounterStatefulCallOptions()` (the common "I have options but no
satoshis opinion" case) through `MockProvider`, without raising, and the
continuation output keeps the spent UTXO's satoshis -- matching the TS
fallback. Also proves an explicit nonzero `options.satoshis` still overrides
that default, so the fix does not disturb existing behaviour.

Does NOT prove: that Go/Rust/Zig/Ruby/Java codegen are free of an analogous
None/0 trap (checked separately — see the dispatcher report for F-239), nor
that every stateful call shape (multi-output, raw-output, terminal) is
covered by this test.
"""

from __future__ import annotations

import json

import pytest

from runar.sdk.codegen import generate_python
from runar.sdk.deployment import build_p2pkh_script
from runar.sdk.local_signer import LocalSigner
from runar.sdk.provider import MockProvider
from runar.sdk.types import DeployOptions, RunarArtifact, Utxo

compiler = pytest.importorskip("runar_compiler.compiler")

KEY = "00" * 31 + "07"

SRC = '''from runar import StatefulSmartContract, Bigint, public


class Counter(StatefulSmartContract):
    count: Bigint

    def __init__(self, count: Bigint):
        super().__init__(count)
        self.count = count

    @public
    def increment(self):
        self.count = self.count + 1
'''


def _artifact() -> RunarArtifact:
    result = compiler.compile_from_source_str_with_result(SRC, "Counter.runar.py")
    errs = [d.message for d in result.diagnostics if d.severity == "error"]
    assert result.artifact is not None, errs
    return RunarArtifact.from_dict(json.loads(compiler.artifact_to_json(result.artifact)))


def _load_generated_wrapper(artifact: RunarArtifact):
    """Generate the typed wrapper source and exec it into a fresh module
    namespace -- exactly the code `runar codegen` would write to disk."""
    code = generate_python(artifact)
    ns: dict = {}
    exec(compile(code, "<generated CounterContract>", "exec"), ns)
    return ns["CounterContract"], ns["CounterStatefulCallOptions"]


def _funded_provider_and_signer() -> tuple[MockProvider, LocalSigner]:
    provider = MockProvider("testnet")
    signer = LocalSigner(KEY)
    provider.add_utxo(signer.get_address(), Utxo(
        txid=KEY[:64], output_index=0, satoshis=500_000,
        script=build_p2pkh_script(signer.get_public_key()),
    ))
    return provider, signer


def test_generated_wrapper_stateful_call_with_default_options_does_not_raise():
    """RED (pre-fix): CounterStatefulCallOptions() defaults satoshis to 0,
    the generated call's `_to_call_options()` turned that into None, and
    `RunarContract.call`'s `if opts.satoshis > 0:` raised TypeError."""
    artifact = _artifact()
    CounterContract, CounterStatefulCallOptions = _load_generated_wrapper(artifact)
    provider, signer = _funded_provider_and_signer()

    wrapper = CounterContract(artifact, count=5)
    wrapper.deploy(provider, signer, DeployOptions(satoshis=1_000))

    # Caller passes an options object (e.g. to reach another field later)
    # but does not set satoshis -- the case the bug report describes.
    wrapper.increment(options=CounterStatefulCallOptions(), provider=provider, signer=signer)

    # GREEN: continuation falls back to the spent UTXO's satoshis (TS
    # parity), not a crash and not a spurious 0.
    assert wrapper.contract.get_state()["count"] == 6
    assert wrapper.contract._current_utxo.satoshis == 1_000


def test_generated_wrapper_explicit_satoshis_still_wins():
    """An explicit, nonzero options.satoshis must still override the UTXO
    default -- the fix must not disturb this existing behaviour."""
    artifact = _artifact()
    CounterContract, CounterStatefulCallOptions = _load_generated_wrapper(artifact)
    provider, signer = _funded_provider_and_signer()

    wrapper = CounterContract(artifact, count=5)
    wrapper.deploy(provider, signer, DeployOptions(satoshis=1_000))

    wrapper.increment(
        options=CounterStatefulCallOptions(satoshis=2_500), provider=provider, signer=signer,
    )

    assert wrapper.contract._current_utxo.satoshis == 2_500
