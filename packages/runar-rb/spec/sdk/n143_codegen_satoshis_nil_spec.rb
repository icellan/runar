# frozen_string_literal: true

require 'spec_helper'
require 'tmpdir'
require 'runar/sdk'

# N-143 (Ruby twin of F-239): the Ruby SDK's generated typed wrappers turn a
# stateful call's default satoshis into nil for every call made with an
# options object that doesn't set satoshis explicitly.
#
# `codegen.rb`'s `{Contract}StatefulCallOptions#to_call_options` built
# `Runar::SDK::CallOptions.new(satoshis: satoshis.positive? ? satoshis : nil,
# ...)` -- the struct's own declared default (`satoshis: 0`) came back out as
# `nil`. `contract.rb`'s stateful-call path then ran `opts.satoshis.positive?`
# unguarded in two places (the `_newAmount` interpreter arg, and
# `build_continuation`'s `new_satoshis` selection) -- both raise
# `NoMethodError: undefined method 'positive?' for nil` the moment a generated
# wrapper's stateful method is called with an options object that doesn't set
# satoshis, which is the common case (every call whose options exist only to
# reach another field, or the plain "no options opinion" default).
#
# Matches the TS SDK: `CallOptions.satoshis` is "unspecified" when the caller
# doesn't set it, and the SDK falls back to the spent UTXO's value
# (packages/runar-sdk/src/contract.ts -- `options?.satoshis ?? ... ??
# this.currentUtxo.satoshis`, using `??` so nil/undefined -- not 0 -- means
# "unset"). The Ruby `CallOptions#satoshis` field already uses 0 as that same
# sentinel (`contract.rb`: `opts.satoshis.positive?`); codegen's
# `satoshis.positive? ? satoshis : nil` broke the type contract on top of that
# without changing the sentinel's meaning.
#
# Proves: a wrapper generated by `Runar::SDK::Codegen.generate_ruby` for a
# real compiled stateful contract (Counter) can make a stateful call through
# `MockProvider` with a freshly constructed `CounterStatefulCallOptions.new`
# (options present, satoshis unset) without raising, and the continuation
# keeps the spent UTXO's satoshis -- matching the TS fallback. Also proves an
# explicit nonzero `options.satoshis` still overrides that default.
#
# Does NOT prove: multi-output, raw-output or terminal call branches; nor that
# Go/Rust/Zig/Java codegen are free of an analogous nil/0 trap (Python was
# fixed separately as F-239; Java's generated wrapper has its own open item,
# N-144).
# rubocop:disable RSpec/DescribeClass
RSpec.describe 'N-143 generated Ruby wrapper stateful call with default options' do
  # rubocop:enable RSpec/DescribeClass

  let(:caller_address) { '00' * 20 }
  let(:caller_pub_key) { '02' + ('00' * 32) }

  COUNTER_SRC = <<~RUBY
    require 'runar'

    class Counter < Runar::StatefulSmartContract
      prop :count, Bigint

      def initialize(count)
        super(count)
        @count = count
      end

      runar_public
      def increment
        @count = @count + 1
      end
    end
  RUBY

  def load_artifact(dir)
    compiler_lib = File.expand_path('../../../../compilers/ruby/lib', __dir__)
    $LOAD_PATH.unshift(compiler_lib) unless $LOAD_PATH.include?(compiler_lib)
    require 'runar_compiler'
    path = File.join(dir, 'Counter.runar.rb')
    File.write(path, COUNTER_SRC)
    Runar::SDK::RunarArtifact.from_json(RunarCompiler.artifact_to_json(RunarCompiler.compile_from_source(path)))
  end

  # Generates the wrapper source for +artifact+ and evals it so the real
  # `CounterContract` / `CounterStatefulCallOptions` classes exist, exactly as
  # `runar codegen` would write them to disk and `require` them.
  def load_generated_wrapper(artifact)
    src = Runar::SDK::Codegen.generate_ruby(artifact)
    # Safe: `src` is this process's own `Codegen.generate_ruby` output for a
    # locally-compiled fixture, not external/untrusted input -- this mirrors
    # what `runar codegen` writes to disk and the caller `require`s.
    eval(src, TOPLEVEL_BINDING, 'generated_counter_wrapper.rb') # rubocop:disable Security/Eval
    [Runar::Contracts::CounterContract, Runar::Contracts::CounterStatefulCallOptions]
  end

  def funded_provider_and_signer
    provider = Runar::SDK::MockProvider.new
    signer   = Runar::SDK::MockSigner.new(pub_key_hex: caller_pub_key, address: caller_address)
    provider.add_utxo(caller_address, Runar::SDK::Utxo.new(
                         txid: 'ee' * 32, output_index: 0, satoshis: 1_000_000,
                         script: "76a914#{caller_address}88ac"
                       ))
    [provider, signer]
  end

  it 'does not raise, and the continuation keeps the spent UTXO satoshis' do
    Dir.mktmpdir do |dir|
      artifact = load_artifact(dir)
      counter_contract_class, counter_stateful_call_options_class = load_generated_wrapper(artifact)
      provider, signer = funded_provider_and_signer

      wrapper = counter_contract_class.new(artifact, count: 5)
      wrapper.connect(provider, signer)
      wrapper.deploy(provider: provider, signer: signer, options: Runar::SDK::DeployOptions.new(satoshis: 1_000))

      # RED (pre-fix): CounterStatefulCallOptions.new defaults satoshis to 0,
      # to_call_options turned that into nil, and contract.rb's unguarded
      # `opts.satoshis.positive?` raised NoMethodError.
      expect do
        wrapper.increment(options: counter_stateful_call_options_class.new, provider: provider, signer: signer)
      end.not_to raise_error

      # GREEN: continuation falls back to the spent UTXO's satoshis (TS
      # parity), not a crash and not a spurious 0.
      expect(wrapper.contract.get_state['count']).to eq(6)
      expect(wrapper.contract.get_utxo.satoshis).to eq(1_000)
    end
  end

  it 'still honours an explicit nonzero options.satoshis' do
    Dir.mktmpdir do |dir|
      artifact = load_artifact(dir)
      counter_contract_class, counter_stateful_call_options_class = load_generated_wrapper(artifact)
      provider, signer = funded_provider_and_signer

      wrapper = counter_contract_class.new(artifact, count: 5)
      wrapper.connect(provider, signer)
      wrapper.deploy(provider: provider, signer: signer, options: Runar::SDK::DeployOptions.new(satoshis: 1_000))

      wrapper.increment(
        options: counter_stateful_call_options_class.new(satoshis: 2_500), provider: provider, signer: signer
      )

      expect(wrapper.contract.get_utxo.satoshis).to eq(2_500)
    end
  end
end
